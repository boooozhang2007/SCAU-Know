/**
 * 生成带明确时区的时间戳。
 * 入参为北京时间（UTC+8）的本地写法，例如 "2026-11-21T10:30:00"。
 * offsetMin 用于把发布时间前移若干分钟（构造「几分钟前」的层次感）。
 */
const P = (at: string, offsetMin = 0): string => {
  const base = new Date(`${at}+08:00`);
  const t = new Date(base.getTime() - offsetMin * 60 * 1000);
  // 转回北京时间字面量并标注 +08:00，保证服务端与客户端解析一致
  const cst = new Date(t.getTime() + 8 * 3600 * 1000);
  const p = (n: number) => String(n).padStart(2, "0");
  return (
    `${cst.getUTCFullYear()}-${p(cst.getUTCMonth() + 1)}-${p(cst.getUTCDate())}` +
    `T${p(cst.getUTCHours())}:${p(cst.getUTCMinutes())}:${p(cst.getUTCSeconds())}+08:00`
  );
};

